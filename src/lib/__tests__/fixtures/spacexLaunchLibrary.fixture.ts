/**
 * Answers a `launch/previous/` request the way the API does. It never serves
 * more than LL2_PAGE_CAP rows whatever `limit` asks for, it honours
 * `offset`, and it shapes the rows by `mode`.
 */
export function serveLl2PreviousPage(requestUrl: string) {
  const url = new URL(requestUrl);
  const limit = Math.min(Number(url.searchParams.get("limit") ?? 10), LL2_PAGE_CAP);
  const offset = Number(url.searchParams.get("offset") ?? 0);
  const row = url.searchParams.get("mode") === "list" ? LL2_LIST_ROW : LL2_NORMAL_ROW;
  const pageUrl = (pageOffset: number) => {
    const page = new URL(url);
    page.searchParams.set("limit", `${limit}`);
    page.searchParams.set("offset", `${pageOffset}`);
    return page.toString();
  };

  return {
    count: LL2_PREVIOUS_COUNT,
    next: offset + limit < LL2_PREVIOUS_COUNT ? pageUrl(offset + limit) : null,
    previous: offset > 0 ? pageUrl(Math.max(offset - limit, 0)) : null,
    results: LL2_PREVIOUS_LAUNCHES.slice(offset, offset + limit).map(([id, net]) => ({
      ...row,
      id,
      net,
    })),
  };
}
